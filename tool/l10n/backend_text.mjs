// Copies the desktop's translations of its backend message codes
// ("backendText.…") into lib/l10n/backend_text.dart, so errors the computer
// sends show in the phone's language instead of as codes.
//
//   node --experimental-strip-types tool/l10n/backend_text.mjs <DogCodes checkout>
//
// The desktop's locale files are the source of truth; rerun after they change.
import { cpSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { execFileSync } from "node:child_process";

const desktop = resolve(process.argv[2] ?? "../DogCodes");
const app = resolve(new URL("../..", import.meta.url).pathname);
const source = join(desktop, "apps/desktop/src/i18n/locales/ui");
// Desktop locale → app language id (lib/l10n/strings.dart).
const languages = {
  "zh-CN": "zh", "zh-TW": "zh-Hant", en: "en", ja: "ja", ko: "ko", fr: "fr",
  de: "de", es: "es", "pt-BR": "pt-BR", ru: "ru", it: "it",
};

// The locale files import each other without extensions; load a copy that
// Node's type stripping can resolve.
const work = mkdtempSync(join(tmpdir(), "dogcodes-backend-text-"));
const catalogs = {};
try {
  cpSync(source, work, { recursive: true });
  for (const file of readdirSync(work)) {
    const path = join(work, file);
    writeFileSync(path, readFileSync(path, "utf8").replace(/from "\.\/([A-Za-z-]+)"/g, 'from "./$1.ts"'));
  }
  for (const [desktopId, appId] of Object.entries(languages)) {
    const module = await import(join(work, `${desktopId}.ts`));
    const messages = Object.values(module).find(value => value?.backendText);
    if (!messages) throw new Error(`${desktopId}: no backendText block`);
    catalogs[appId] = messages.backendText;
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}

// Parameter names for codes whose values arrive as a JSON array.
const helper = readFileSync(join(desktop, "apps/desktop/src/backendText.ts"), "utf8");
const block = helper.match(/const codeParams[^{]*\{([\s\S]*?)\n\};/);
if (!block) throw new Error("codeParams not found in backendText.ts");
const params = {};
for (const [, code, names] of block[1].matchAll(/"([^"]+)":\s*\[([^\]]*)\]/g)) {
  params[code] = [...names.matchAll(/"([^"]+)"/g)].map(match => match[1]);
}

const keys = Object.keys(catalogs.zh).sort();
for (const [id, catalog] of Object.entries(catalogs)) {
  const missing = keys.filter(key => typeof catalog[key] !== "string");
  if (missing.length) throw new Error(`${id}: ${missing.length} missing, e.g. ${missing[0]}`);
}

const quote = value => JSON.stringify(value).replaceAll("$", "\\$");
const lines = [
  "// Generated by tool/l10n/backend_text.mjs from the desktop's locale files.\n",
  "// Do not edit by hand.\n\n",
  "/// Parameter names, in order, for codes that carry values.\n",
  "const backendTextParams = <String, List<String>>{\n",
  ...Object.entries(params).map(([code, names]) => `  ${quote(code)}: [${names.map(quote).join(", ")}],\n`),
  "};\n\n",
  "/// Message templates by app language, then by code without `backendText.`.\n",
  "const backendTextCatalogs = <String, Map<String, String>>{\n",
];
for (const [id, catalog] of Object.entries(catalogs)) {
  lines.push(`  ${quote(id)}: {\n`);
  for (const key of keys) lines.push(`    ${quote(key)}: ${quote(catalog[key])},\n`);
  lines.push("  },\n");
}
lines.push("};\n");
const output = join(app, "lib/l10n/backend_text_catalog.dart");
writeFileSync(output, lines.join(""));
execFileSync("dart", ["format", output], { stdio: "inherit" });
console.log(`${keys.length} messages in ${Object.keys(catalogs).length} languages → ${output}`);
